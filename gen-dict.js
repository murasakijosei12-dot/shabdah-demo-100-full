/*
   General-dictionary fallback for Hindi and French.

   Japanese and English have always had one: a hovered word that isn't one of
   PTW's curated 5,000 concepts falls through to JMdict (432,572 headwords) or
   to its inversion in en-ja-dictionary.json (225,157 glosses), and the learner
   still gets an answer. Hindi and French had nothing behind the curated set,
   so hovering anything PTW doesn't teach produced silence.

   Backed by data/hi-dictionary.json (22,224 Hindi headwords, inverted from
   FreeDict eng-hin) and data/fr-dictionary.json (55,356 French headwords from
   WOLF mapped onto Princeton WordNet). Both are generated by
   tools/build_hi_fr_dictionaries.py and then filtered by
   tools/clean_gen_dictionaries.py; the credit and licence for each travel
   inside the file as a _credit field.

   Both are FALLBACKS, never curated content. Hindi comes from volunteer-
   compiled Shabdanjali material whose publishers make no claim of uniform
   quality, and ships under the GPL because that is how IIIT Hyderabad
   released it; French is an automatic mapping of Princeton WordNet. Neither
   is presented to a learner as equivalent to PTW's own 5,000 concepts. The
   French FreeDict top-up was removed to keep French free of copyleft.

   Entry shape matches what ptwDictEntryForReading() in ja-lookup.js expects --
   an ARRAY of { gloss: [...], ... } -- so a result built here renders through
   exactly the same popup path as a Japanese dictionary hit.
*/

const PTW_GEN_DICT_URLS = {
  hi: "data/hi-dictionary.json",
  fr: "data/fr-dictionary.json",
};

const ptwGenDictCache = {};
const ptwGenDictLoading = {};

async function ptwLoadGenDict(lang) {
  if (ptwGenDictCache[lang]) return ptwGenDictCache[lang];
  if (ptwGenDictLoading[lang]) return ptwGenDictLoading[lang];
  const url = PTW_GEN_DICT_URLS[lang];
  if (!url) return {};

  ptwGenDictLoading[lang] = (async () => {
    try {
      // Same file is shipped to the website as gen-dict.js, where there is no
      // chrome.runtime and the data sits at a plain relative path. One source
      // of truth for the morphology below is worth the two-line branch here.
      const href = (typeof chrome !== "undefined" && chrome.runtime && chrome.runtime.getURL)
        ? chrome.runtime.getURL(url)
        : url;
      const res = await fetch(href);
      const json = await res.json();
      ptwGenDictCache[lang] = json.words || json;
    } catch (err) {
      console.error("PTW general dictionary load failed:", lang, err);
      ptwGenDictCache[lang] = {};
    }
    return ptwGenDictCache[lang];
  })();

  return ptwGenDictLoading[lang];
}

/* French surface forms.

   Not a morphological analyser -- a short list of the endings that account for
   most of what a reader actually meets, tried longest-first against a
   dictionary of lemmas. Over-generating costs nothing: a form that isn't a
   headword simply doesn't match. */
function ptwFrVariants(word) {
  const w = word.toLowerCase();
  // The word as written comes first: proper nouns are headwords in their own
  // right ("Paris", "Hongroise"), and lowercasing before trying the exact key
  // lost 54 of every 300 headwords in testing.
  const out = word === w ? [w] : [word, w];
  const push = (s) => { if (s && s.length > 1 && out.indexOf(s) === -1) out.push(s); };

  // Plural and feminine agreement.
  if (w.endsWith("aux")) push(w.slice(0, -3) + "al");     // journaux -> journal
  if (w.endsWith("x")) push(w.slice(0, -1));              // choux -> chou
  if (w.endsWith("s")) push(w.slice(0, -1));              // chiens -> chien
  if (w.endsWith("es")) push(w.slice(0, -2));             // grandes -> grand
  if (w.endsWith("e")) push(w.slice(0, -1));              // grande -> grand
  if (w.endsWith("ve")) push(w.slice(0, -2) + "f");       // active -> actif
  if (w.endsWith("ives")) push(w.slice(0, -4) + "if");
  if (w.endsWith("ère")) push(w.slice(0, -3) + "er");     // première -> premier
  if (w.endsWith("euse")) push(w.slice(0, -4) + "eux");   // heureuse -> heureux
  if (w.endsWith("ment")) push(w.slice(0, -4));           // rapidement -> rapide

  // Verbs. The conjugated form is stripped back to a stem, then each of the
  // three infinitive endings is tried, because the stem alone does not say
  // which conjugation class it came from.
  const verbEndings = [
    "eraient", "erions", "assent", "aient", "erait", "erons", "erez", "eront",
    "ions", "iez", "ais", "ait", "ant", "ons", "ez", "ent", "es", "e",
    "é", "ée", "és", "ées", "i", "is", "it", "us", "ut", "a", "as",
  ];
  for (const end of verbEndings) {
    if (w.length > end.length + 1 && w.endsWith(end)) {
      const stem = w.slice(0, -end.length);
      push(stem + "er");
      push(stem + "ir");
      push(stem + "re");
      push(stem);
      // -ger and -cer verbs keep a softening vowel before a back vowel
      // ("mangeons", "commencons"), so the stem carries an extra letter the
      // infinitive does not: mangeons -> mange- -> manger.
      if (stem.endsWith("e") || stem.endsWith("ç")) {
        const bare = stem.slice(0, -1);
        push(bare + "er");
        push(bare + "cer");
      }
      // Second-group -ir verbs insert -iss- outside the singular present:
      // finissons -> finiss- -> finir.
      if (stem.endsWith("iss")) push(stem.slice(0, -3) + "ir");
    }
  }
  return out;
}

/* Hindi surface forms.

   Hindi inflects by suffix on a fairly regular stem, so stripping the common
   case, number and gender endings and trying the bare stem catches most of
   it. Verbs are recovered by re-attaching the -ना infinitive, which is the
   form a dictionary is keyed on. */
function ptwHiVariants(word) {
  const w = word.trim();
  const out = [w];
  const push = (s) => { if (s && s.length > 1 && out.indexOf(s) === -1) out.push(s); };

  const nounEndings = ["ियों", "ाओं", "ओं", "ों", "ें", "ए", "ऍ", "ीं"];
  for (const end of nounEndings) {
    if (w.endsWith(end)) {
      const stem = w.slice(0, -end.length);
      push(stem);
      push(stem + "ा");
      push(stem + "ी");
      push(stem + "ई");
    }
  }
  // Masculine/feminine/oblique alternation on the final vowel.
  if (/[ेीा]$/.test(w)) {
    const stem = w.slice(0, -1);
    push(stem + "ा");
    push(stem + "ी");
    push(stem);
  }

  // Verb participles and stems back to the -ना infinitive.
  const verbEndings = ["ता", "ती", "ते", "या", "यी", "ये", "ेगा", "ेगी", "ेंगे",
                       "कर", "ूंगा", "ूंगी", "ना", "ने", "नी"];
  for (const end of verbEndings) {
    if (w.length > end.length && w.endsWith(end)) {
      const stem = w.slice(0, -end.length);
      push(stem + "ना");
      push(stem);
    }
  }
  if (!w.endsWith("ना")) push(w + "ना");
  return out;
}

function ptwGenDictVariants(lang, word) {
  if (lang === "fr") return ptwFrVariants(word);
  if (lang === "hi") return ptwHiVariants(word);
  return [word];
}

/**
 * Look a word up in the general dictionary for `lang`.
 * @returns {{matched: string, entries: Array}|null}
 */
function ptwGenDictLookup(lang, word, dict) {
  if (!dict || !word) return null;
  for (const variant of ptwGenDictVariants(lang, word)) {
    const entries = dict[variant];
    if (entries && entries.length) return { matched: variant, entries };
  }
  return null;
}

/**
 * Wrap a general-dictionary hit in the result shape ptwRenderPopup expects.
 * conceptId stays null -- this is explicitly NOT one of the curated concepts,
 * and the popup already renders that case from `dictionaryEntry`.
 */
function ptwGenDictResult(lang, surfaceForm, hit) {
  return {
    lemma: hit.matched,
    surfaceForm: surfaceForm,
    reading: "",
    speakText: hit.matched,
    conceptId: null,
    dictionaryEntry: hit.entries,
    form: { form_id: lang + "_dictionary", label: { en: "", hi: "", ja: "", fr: "" }, tokensConsumed: 0 },
    foundInDictionary: true,
    _isGeneralDictionary: true,
  };
}

